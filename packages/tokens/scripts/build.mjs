// Generate token outputs from brand/tokens.json (the source of truth).
//   src/generated.ts  typed object for React Native and TS code
//   tokens.css        CSS variables + Tailwind v4 theme for the web app
// Run: pnpm tokens   (CI fails if outputs are stale; see test/generated.test.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(pkg, "..", "..", "brand", "tokens.json");

export function render() {
  const t = JSON.parse(readFileSync(source, "utf8"));
  const strip = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k.startsWith("$") ? undefined : v)));
  const clean = strip(t);

  const ts =
    "// Generated by packages/tokens/scripts/build.mjs from brand/tokens.json. Do not edit.\n" +
    `export const tokens = ${JSON.stringify(clean, null, 2)} as const;\n`;

  const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const light = clean.color.role.light;
  const dark = clean.color.role.dark;
  const brand = clean.color.brand;
  const status = clean.color.status;
  const neutral = clean.color.neutral;

  const vars = (o, indent = "  ") =>
    Object.entries(o)
      .map(([k, v]) => `${indent}--lb-${kebab(k)}: ${v};`)
      .join("\n");

  const css = [
    "/* Generated by packages/tokens/scripts/build.mjs from brand/tokens.json. Do not edit. */",
    ":root {",
    vars(brand),
    vars(status),
    Object.entries(neutral)
      .map(([k, v]) => `  --lb-neutral-${k}: ${v};`)
      .join("\n"),
    vars(light),
    `  --lb-font-display: "${clean.font.display.family}", "Arial Narrow", "Roboto Condensed", sans-serif;`,
    `  --lb-font-body: "${clean.font.body.family}", "Segoe UI", Roboto, Helvetica, Arial, sans-serif;`,
    "}",
    "",
    '[data-theme="dark"] {',
    vars(dark),
    "  color-scheme: dark;",
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    vars(dark, "    "),
    "    color-scheme: dark;",
    "  }",
    "}",
    "",
    "/* Tailwind v4 theme: utilities like bg-surface, text-muted, bg-primary, font-display. */",
    "@theme inline {",
    ...Object.keys(light).map((k) => `  --color-${kebab(k)}: var(--lb-${kebab(k)});`),
    ...Object.keys(brand).map((k) => `  --color-${kebab(k)}: var(--lb-${kebab(k)});`),
    ...Object.keys(status).map((k) => `  --color-status-${kebab(k)}: var(--lb-${kebab(k)});`),
    // Brand neutrals replace Tailwind's default gray scale.
    "  --color-neutral-*: initial;",
    ...Object.keys(clean.color.neutral).map(
      (k) => `  --color-neutral-${k}: var(--lb-neutral-${k});`,
    ),
    "  --font-display: var(--lb-font-display);",
    "  --font-sans: var(--lb-font-body);",
    ...Object.entries(clean.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    "}",
    "",
  ].join("\n");

  return { ts, css };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { ts, css } = render();
  writeFileSync(join(pkg, "src", "generated.ts"), ts);
  writeFileSync(join(pkg, "tokens.css"), css);
  console.log("wrote src/generated.ts and tokens.css");
}
