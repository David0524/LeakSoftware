// Generate token outputs from brand/tokens.json (the source of truth).
//   src/generated.ts  typed object for React Native and TS code
//   tokens.css        CSS variables + Tailwind v4 theme for the web app
//   apps/ios/Sources/SundeckTokens/Tokens.swift   the iPhone app (Swift)
// Run: pnpm tokens   (CI fails if outputs are stale; see test/generated.test.ts)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(pkg, "..", "..", "brand", "tokens.json");
export const swiftPath = join(
  pkg,
  "..",
  "..",
  "apps",
  "ios",
  "Sources",
  "SundeckTokens",
  "Tokens.swift",
);

/** Brand fonts the iPhone app bundles (titles in Barlow; body text is the system font). */
export const iosFonts = [
  "BarlowSemiCondensed-SemiBold.ttf",
  "BarlowSemiCondensed-Bold.ttf",
  "BarlowSemiCondensed-ExtraBold.ttf",
  "OFL-BarlowSemiCondensed.txt",
].map((name) => ({
  from: join(pkg, "..", "..", "brand", "fonts", name),
  to: join(dirname(swiftPath), "Fonts", name),
}));

export function render() {
  const t = JSON.parse(readFileSync(source, "utf8"));
  const strip = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k.startsWith("$") ? undefined : v)));
  const clean = strip(t);

  const ts =
    "// Generated by packages/tokens/scripts/build.mjs from brand/tokens.json. Do not edit.\n" +
    `export const tokens = ${JSON.stringify(clean, null, 2)} as const;\n`;

  const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const light = clean.color.role.light;
  const dark = clean.color.role.dark;
  const brand = clean.color.brand;
  const status = clean.color.status;
  const neutral = clean.color.neutral;

  const vars = (o, indent = "  ") =>
    Object.entries(o)
      .map(([k, v]) => `${indent}--lb-${kebab(k)}: ${v};`)
      .join("\n");

  const css = [
    "/* Generated by packages/tokens/scripts/build.mjs from brand/tokens.json. Do not edit. */",
    ":root {",
    vars(brand),
    vars(status),
    Object.entries(neutral)
      .map(([k, v]) => `  --lb-neutral-${k}: ${v};`)
      .join("\n"),
    vars(light),
    // Pool diagram landmarks: --lb-landmark-leaf, ... (the same in dark).
    Object.entries(clean.color.landmark)
      .map(([k, v]) => `  --lb-landmark-${kebab(k)}: ${v};`)
      .join("\n"),
    `  --lb-font-display: "${clean.font.display.family}", "Arial Narrow", "Roboto Condensed", sans-serif;`,
    `  --lb-font-body: "${clean.font.body.family}", "Segoe UI", Roboto, Helvetica, Arial, sans-serif;`,
    "}",
    "",
    '[data-theme="dark"] {',
    vars(dark),
    "  color-scheme: dark;",
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    vars(dark, "    "),
    "    color-scheme: dark;",
    "  }",
    "}",
    "",
    "/* Always light, whatever the viewer's setting: printed and customer documents. */",
    ".lb-light {",
    vars(status),
    vars(light),
    "  color-scheme: light;",
    "}",
    "",
    "/* Tailwind v4 theme: utilities like bg-surface, text-muted, bg-primary, font-display. */",
    "@theme inline {",
    ...Object.keys(light).map((k) => `  --color-${kebab(k)}: var(--lb-${kebab(k)});`),
    ...Object.keys(brand).map((k) => `  --color-${kebab(k)}: var(--lb-${kebab(k)});`),
    ...Object.keys(status).map((k) => `  --color-status-${kebab(k)}: var(--lb-${kebab(k)});`),
    ...Object.keys(clean.color.landmark).map(
      (k) => `  --color-landmark-${kebab(k)}: var(--lb-landmark-${kebab(k)});`,
    ),
    // Brand neutrals replace Tailwind's default gray scale.
    "  --color-neutral-*: initial;",
    ...Object.keys(clean.color.neutral).map(
      (k) => `  --color-neutral-${k}: var(--lb-neutral-${k});`,
    ),
    "  --font-display: var(--lb-font-display);",
    "  --font-sans: var(--lb-font-body);",
    ...Object.entries(clean.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    "}",
    "",
  ].join("\n");

  return { ts, css, swift: renderSwift(clean) };
}

/** The iPhone app's tokens: colors as 8-bit channels, light and dark per role. */
function renderSwift(clean) {
  const channels = (hex) => {
    const h = hex.replace("#", "");
    const parts = [
      h.slice(0, 2),
      h.slice(2, 4),
      h.slice(4, 6),
      h.length === 8 ? h.slice(6, 8) : "FF",
    ];
    return parts.map((p) => `0x${p.toUpperCase()}`).join(", ");
  };
  const color = (hex) => `TokenColor(${channels(hex)})`;
  const status = clean.color.status;
  const { light, dark } = clean.color.role;
  // Roles the light theme takes from the status colors (dark has its own).
  const roles = [...new Set([...Object.keys(light), ...Object.keys(dark)])];
  const lines = [
    "// Generated by packages/tokens/scripts/build.mjs from brand/tokens.json. Do not edit.",
    "// Run `pnpm tokens` after changing brand/tokens.json.",
    "",
    "/// A color as 8-bit red, green, blue and opacity.",
    "public struct TokenColor: Equatable, Sendable {",
    "    public let red: UInt8",
    "    public let green: UInt8",
    "    public let blue: UInt8",
    "    public let opacity: UInt8",
    "",
    "    public init(_ red: UInt8, _ green: UInt8, _ blue: UInt8, _ opacity: UInt8) {",
    "        self.red = red",
    "        self.green = green",
    "        self.blue = blue",
    "        self.opacity = opacity",
    "    }",
    "}",
    "",
    "/// One role's color in the light and the dark appearance.",
    "public struct TokenRole: Equatable, Sendable {",
    "    public let light: TokenColor",
    "    public let dark: TokenColor",
    "",
    "    public init(light: TokenColor, dark: TokenColor) {",
    "        self.light = light",
    "        self.dark = dark",
    "    }",
    "}",
    "",
    "/// Sundeck Pro's design tokens (brand/BRAND.md).",
    "public enum Tokens {",
    "    public enum Brand {",
    ...Object.entries(clean.color.brand).map(
      ([k, v]) => `        public static let ${k} = ${color(v)}`,
    ),
    "    }",
    "",
    "    public enum Status {",
    ...Object.entries(status).map(([k, v]) => `        public static let ${k} = ${color(v)}`),
    "    }",
    "",
    "    public enum Neutral {",
    ...Object.entries(clean.color.neutral).map(
      ([k, v]) => `        public static let n${k} = ${color(v)}`,
    ),
    "    }",
    "",
    "    /// Pool diagram landmarks, the same in light and dark.",
    "    public enum Landmark {",
    ...Object.entries(clean.color.landmark).map(
      ([k, v]) => `        public static let ${k} = ${color(v)}`,
    ),
    "    }",
    "",
    "    public enum Markup {",
    ...Object.entries(clean.color.markup).map(
      ([k, v]) => `        public static let ${k} = ${color(v)}`,
    ),
    "    }",
    "",
    "    /// Colors by role, for both appearances.",
    "    public enum Role {",
    ...roles.map((k) => {
      const l = light[k] ?? status[k];
      return [
        `        public static let ${k} = TokenRole(`,
        `            light: ${color(l)}, dark: ${color(dark[k] ?? l)})`,
      ].join("\n");
    }),
    "    }",
    "",
    "    public enum Radius {",
    ...Object.entries(clean.radius).map(
      ([k, v]) => `        public static let ${k}: Double = ${v}`,
    ),
    "    }",
    "",
    "    public enum Space {",
    ...Object.entries(clean.space).map(
      ([k, v]) => `        public static let s${k}: Double = ${v}`,
    ),
    "    }",
    "",
    "    /// Minimum tap target in the field app (gloves, wet hands).",
    `    public static let minTarget: Double = ${clean.touch.minTarget}`,
    "}",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { ts, css, swift } = render();
  writeFileSync(join(pkg, "src", "generated.ts"), ts);
  writeFileSync(join(pkg, "tokens.css"), css);
  writeFileSync(swiftPath, swift);
  mkdirSync(join(dirname(swiftPath), "Fonts"), { recursive: true });
  for (const f of iosFonts) copyFileSync(f.from, f.to);
  console.log("wrote src/generated.ts, tokens.css, and the iPhone app's Tokens.swift and fonts");
}
