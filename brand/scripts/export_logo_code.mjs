// Turn the horizontal logo SVGs into drawing data for the native apps, so they draw the lockup
// as vectors (sharp at every size) from the same geometry as the website's SVG files.
// Run after build_logo.py: node brand/scripts/export_logo_code.mjs
//
// Writes:
//   apps/ios/Sources/SundeckApp/UI/SundeckLogoArt.swift   (SwiftUI, SundeckLogo in BrandLogo.swift)
//   apps/mobile/src/ui/sundeckLogoArt.ts                  (react-native-svg, ui/SundeckLogo.tsx)
//
// Each path is rewritten in absolute M, L, C, A and Z commands in the lockup's own coordinates
// (the SVG's group translations applied, quadratic curves raised to cubic), so the apps need no
// transforms and the Swift path parser needs no Q support.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const logo = join(root, "brand", "logo");

const r = (v) => {
  const s = (Math.round(v * 100) / 100).toFixed(2).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};

/** An SVG path's d, in absolute commands, translated by (tx, ty). */
function normalize(d, tx, ty) {
  const tokens = d.match(/[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g);
  let i = 0;
  const num = () => Number(tokens[i++]);
  const out = [];
  let cx = 0,
    cy = 0,
    sx = 0,
    sy = 0,
    cmd = "";
  const P = (x, y) => `${r(x + tx)} ${r(y + ty)}`;
  while (i < tokens.length) {
    if (/[A-Za-z]/.test(tokens[i])) cmd = tokens[i++];
    const rel = cmd === cmd.toLowerCase();
    const bx = rel ? cx : 0;
    const by = rel ? cy : 0;
    switch (cmd.toUpperCase()) {
      case "M": {
        cx = bx + num();
        cy = by + num();
        sx = cx;
        sy = cy;
        out.push(`M${P(cx, cy)}`);
        cmd = rel ? "l" : "L";
        break;
      }
      case "L": {
        cx = bx + num();
        cy = by + num();
        out.push(`L${P(cx, cy)}`);
        break;
      }
      case "H": {
        cx = (rel ? cx : 0) + num();
        out.push(`L${P(cx, cy)}`);
        break;
      }
      case "V": {
        cy = (rel ? cy : 0) + num();
        out.push(`L${P(cx, cy)}`);
        break;
      }
      case "C": {
        const a = [bx + num(), by + num()];
        const b = [bx + num(), by + num()];
        cx = bx + num();
        cy = by + num();
        out.push(`C${P(...a)} ${P(...b)} ${P(cx, cy)}`);
        break;
      }
      case "Q": {
        const q = [bx + num(), by + num()];
        const x = bx + num();
        const y = by + num();
        const a = [cx + (2 / 3) * (q[0] - cx), cy + (2 / 3) * (q[1] - cy)];
        const b = [x + (2 / 3) * (q[0] - x), y + (2 / 3) * (q[1] - y)];
        cx = x;
        cy = y;
        out.push(`C${P(...a)} ${P(...b)} ${P(cx, cy)}`);
        break;
      }
      case "A": {
        const rx = num(),
          ry = num(),
          rot = num(),
          large = num(),
          sweep = num();
        cx = bx + num();
        cy = by + num();
        out.push(`A${r(rx)} ${r(ry)} ${r(rot)} ${large} ${sweep} ${P(cx, cy)}`);
        break;
      }
      case "Z": {
        cx = sx;
        cy = sy;
        out.push("Z");
        break;
      }
      default:
        throw new Error(`Unsupported path command ${cmd}`);
    }
  }
  return out.join(" ");
}

/** The lockup's layers, bottom first: { d, fill, evenOdd }, plus its size. */
async function layers(file) {
  const svg = await readFile(join(logo, file), "utf8");
  const [, , w, h] = svg
    .match(/viewBox="([^"]+)"/)[1]
    .split(/\s+/)
    .map(Number);
  const out = [];
  for (const g of svg.matchAll(
    /<g transform="translate\(([-\d.]+) ([-\d.]+)\)[^"]*">(.*?)<\/g>/g,
  )) {
    const [tx, ty] = [Number(g[1]), Number(g[2])];
    for (const p of g[3].matchAll(/<path ([^>]*)\/>/g)) {
      const attr = (name) => p[1].match(new RegExp(`${name}="([^"]+)"`))?.[1];
      out.push({
        d: normalize(attr("d"), tx, ty),
        fill: attr("fill"),
        evenOdd: attr("fill-rule") === "evenodd",
      });
    }
  }
  return { w, h, layers: out };
}

const light = await layers("sundeck-logo.svg");
const dark = await layers("sundeck-logo-reverse.svg");
if (light.w !== dark.w || light.h !== dark.h) throw new Error("Lockups differ in size");

// Name each distinct path once (the wordmark is the same in both).
const names = new Map();
const nameFor = (d) => {
  if (!names.has(d)) names.set(d, `path${names.size}`);
  return names.get(d);
};
for (const l of [...light.layers, ...dark.layers]) nameFor(l.d);

const header = (c) =>
  `${c} Generated by brand/scripts/export_logo_code.mjs from brand/logo/sundeck-logo.svg (light)\n` +
  `${c} and sundeck-logo-reverse.svg (dark). Do not edit; edit build_logo.py and re-run both.\n`;

// Swift: strings cut into lines under swift-format's 120 columns.
function swiftString(d, indent) {
  const parts = [];
  let line = "";
  for (const word of d.split(" ")) {
    if (line && line.length + word.length + 1 > 96) {
      parts.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) parts.push(line);
  if (parts.length === 1) return `"${parts[0]}"`;
  const pad = " ".repeat(indent);
  return `[\n${parts.map((p) => `${pad}    "${p}",`).join("\n")}\n${pad}].joined(separator: " ")`;
}
const swiftLayer = (l) =>
  `            Layer(d: ${nameFor(l.d)}, hex: "${l.fill}", evenOdd: ${l.evenOdd}),`;
const swift = `${header("//")}
import Foundation

/// The horizontal Sundeck Pro lockup as vector layers, bottom first (light: on light
/// backgrounds; dark: the reverse lockup, all-white wordmark).
enum SundeckLogoArt {
    struct Layer: Sendable {
        let d: String
        let hex: String
        let evenOdd: Bool
    }

    static let size = CGSize(width: ${light.w}, height: ${light.h})

    static let light: [Layer] = [
${light.layers
  .map(swiftLayer)
  .join("\n")
  .replace(/^ {12}/gm, "        ")}
    ]

    static let dark: [Layer] = [
${dark.layers
  .map(swiftLayer)
  .join("\n")
  .replace(/^ {12}/gm, "        ")}
    ]
${[...names].map(([d, n]) => `\n    private static let ${n} = ${swiftString(d, 4)}`).join("\n")}
}
`;

const tsLayer = (l) =>
  `  { d: ${nameFor(l.d)}, fill: "${l.fill}"${l.evenOdd ? ", evenOdd: true" : ""} },`;
const ts = `${header("//")}
export interface LogoLayer {
  d: string;
  fill: string;
  evenOdd?: boolean;
}

${[...names]
  .map(([d, n]) => {
    // As Prettier prints it (100 columns): one line when it fits.
    const one = `const ${n} = "${d}";`;
    return one.length <= 100 ? one : `const ${n} =\n  "${d}";`;
  })
  .join("\n")}

/** The lockup's size, in its own units. */
export const LOGO_SIZE = { width: ${light.w}, height: ${light.h} };

/** On light backgrounds, bottom first. */
export const LOGO_LIGHT: LogoLayer[] = [
${light.layers.map(tsLayer).join("\n")}
];

/** The reverse lockup for dark backgrounds, bottom first. */
export const LOGO_DARK: LogoLayer[] = [
${dark.layers.map(tsLayer).join("\n")}
];
`;

const swiftOut = join(root, "apps/ios/Sources/SundeckApp/UI/SundeckLogoArt.swift");
const tsOut = join(root, "apps/mobile/src/ui/sundeckLogoArt.ts");
await writeFile(swiftOut, swift);
await writeFile(tsOut, ts);
